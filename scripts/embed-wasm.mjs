import fs from 'node:fs';
import path from 'node:path';

const rootDir = process.cwd();
const wasmSrcPath = path.resolve(
  rootDir,
  'target',
  'wasm32-unknown-unknown',
  'release',
  'open_velo_core.wasm'
);

if (!fs.existsSync(wasmSrcPath)) {
  console.error(`Missing compiled WASM binary at ${wasmSrcPath}`);
  process.exit(1);
}

const wasmBytes = fs.readFileSync(wasmSrcPath);
const base64 = wasmBytes.toString('base64');

const outTsPath = path.resolve(rootDir, 'src', 'wasm', 'embeddedWasm.ts');
fs.mkdirSync(path.dirname(outTsPath), { recursive: true });

const content = `// AUTO-GENERATED BY scripts/embed-wasm.mjs — DO NOT EDIT MANUALLY
// Contains the compiled open-velo-core (open_velo_core.wasm) binary (${wasmBytes.byteLength} bytes)
// so any browser frontend can instantiate the Rust engine without external .wasm asset configuration.

export const EMBEDDED_WASM_BASE64 = '${base64}';

export function decodeEmbeddedWasmBytes(): Uint8Array {
  const binaryString = atob(EMBEDDED_WASM_BASE64);
  const bytes = new Uint8Array(binaryString.length);
  for (let i = 0; i < binaryString.length; i++) {
    bytes[i] = binaryString.charCodeAt(i);
  }
  return bytes;
}
`;

fs.writeFileSync(outTsPath, content, 'utf-8');
console.log(
  `Embedded ${wasmBytes.byteLength} bytes of open_velo_core.wasm into src/wasm/embeddedWasm.ts`
);
